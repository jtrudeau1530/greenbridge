from __future__ import annotations

"""Semantic reference oracle and architectural model for AMD RDNA2 v_sad_hi_u32.

AMD RDNA VALU Instruction Set Architecture:
  v_sad_hi_u32 dst, src0, src1, src2

Format:
  VOP3 (3-operand vector ALU instruction).

Operation:
  Computes the high 32-bit carry/overflow word of the full 64-bit sum of
  unsigned absolute differences with 32-bit accumulation:
    diff    = |src0.u32 - src1.u32| = (src0 >= src1) ? (src0 - src1) : (src1 - src0)
    sum64   = diff + src2.u32
    dst.u32 = (sum64 >> 32) & 0xFFFFFFFF

Mathematical Properties and Bounds:
  - Operands src0, src1, src2 are unsigned 32-bit integers in [0, 2^32 - 1].
  - Absolute difference diff is in [0, 2^32 - 1] (0 to 0xFFFFFFFF).
  - Accumulation sum64 = diff + src2 is in [0, 2 * (2^32 - 1)] = [0, 0x1FFFFFFFE].
  - Consequently, (sum64 >> 32) is strictly bounded in {0, 1}.
  - v_sad_hi_u32 computes the exact carry-out generated by adding |src0 - src1| to src2.
  - Multi-precision 64-bit reconstruction with complementary v_sad_u32:
      ((v_sad_hi_u32(s0, s1, s2) << 32) | v_sad_u32(s0, s1, s2)) == |src0 - src1| + src2.
"""

from dataclasses import dataclass, field
from enum import Enum, auto
from typing import List, Optional, Tuple, Union
import unittest

# Architectural bitmasks
MASK32: int = 0xFFFF_FFFF
MASK64: int = 0xFFFF_FFFF_FFFF_FFFF


def u32(val: int) -> int:
    """Normalize integer to unsigned 32-bit dword."""
    return val & MASK32


def u64(val: int) -> int:
    """Normalize integer to unsigned 64-bit qword."""
    return val & MASK64


def ref_abs_diff_u32(s0: int, s1: int) -> int:
    """Pure-Python reference oracle for 32-bit unsigned absolute difference: |s0 - s1|."""
    u0 = s0 & MASK32
    u1 = s1 & MASK32
    return (u0 - u1) if u0 >= u1 else (u1 - u0)


def ref_sad_u32(s0: int, s1: int, s2: int) -> int:
    """Reference mathematical oracle for low 32-bit sum of absolute differences."""
    diff = ref_abs_diff_u32(s0, s1)
    acc = s2 & MASK32
    return (diff + acc) & MASK32


def ref_sad_hi_u32(s0: int, s1: int, s2: int) -> int:
    """Reference mathematical oracle for high 32-bit carry word of v_sad_hi_u32."""
    diff = ref_abs_diff_u32(s0, s1)
    acc = s2 & MASK32
    sum64 = diff + acc
    return (sum64 >> 32) & MASK32


def ref_sad_full_64(s0: int, s1: int, s2: int) -> Tuple[int, int, int]:
    """Return (lo32, hi32, full64) for (|src0 - src1| + src2)."""
    diff = ref_abs_diff_u32(s0, s1)
    acc = s2 & MASK32
    sum64 = diff + acc
    lo = sum64 & MASK32
    hi = (sum64 >> 32) & MASK32
    return lo, hi, sum64


