from __future__ import annotations

"""Semantic reference oracle and architectural model for AMD RDNA2 v_sad_hi_u32.

AMD RDNA VALU Instruction Set Architecture:
  v_sad_hi_u32 dst, src0, src1, src2

Format:
  VOP3 (3-operand vector ALU instruction).

Operation:
  Computes the high 32-bit carry/overflow word of the full 64-bit sum of
  unsigned absolute differences with 32-bit accumulation:
    diff    = |src0.u32 - src1.u32| = (src0 >= src1) ? (src0 - src1) : (src1 - src0)
    sum64   = diff + src2.u32
    dst.u32 = (sum64 >> 32) & 0xFFFFFFFF

Mathematical Properties and Bounds:
  - Operands src0, src1, src2 are unsigned 32-bit integers in [0, 2^32 - 1].
  - Absolute difference diff is in [0, 2^32 - 1] (0 to 0xFFFFFFFF).
  - Accumulation sum64 = diff + src2 is in [0, 2 * (2^32 - 1)] = [0, 0x1FFFFFFFE].
  - Consequently, (sum64 >> 32) is strictly bounded in {0, 1}.
  - v_sad_hi_u32 computes the exact carry-out generated by adding |src0 - src1| to src2.
  - Multi-precision 64-bit reconstruction with complementary v_sad_u32:
      ((v_sad_hi_u32(s0, s1, s2) << 32) | v_sad_u32(s0, s1, s2)) == |src0 - src1| + src2.
"""

from typing import List, Optional, Tuple, Union
import unittest

# Architectural bitmasks
MASK32: int = 0xFFFF_FFFF
MASK64: int = 0xFFFF_FFFF_FFFF_FFFF


def u32(val: int) -> int:
    """Normalize integer to unsigned 32-bit dword."""
    return val & MASK32


def u64(val: int) -> int:
    """Normalize integer to unsigned 64-bit qword."""
    return val & MASK64


def ref_abs_diff_u32(s0: int, s1: int) -> int:
    """Pure-Python reference oracle for 32-bit unsigned absolute difference: |s0 - s1|."""
    u0 = s0 & MASK32
    u1 = s1 & MASK32
    return (u0 - u1) if u0 >= u1 else (u1 - u0)


def ref_sad_u32(s0: int, s1: int, s2: int) -> int:
    """Reference mathematical oracle for low 32-bit sum of absolute differences."""
    diff = ref_abs_diff_u32(s0, s1)
    acc = s2 & MASK32
    return (diff + acc) & MASK32


def ref_sad_hi_u32(s0: int, s1: int, s2: int) -> int:
    """Reference mathematical oracle for high 32-bit carry word of v_sad_hi_u32."""
    diff = ref_abs_diff_u32(s0, s1)
    acc = s2 & MASK32
    sum64 = diff + acc
    return (sum64 >> 32) & MASK32


def ref_sad_full_64(s0: int, s1: int, s2: int) -> Tuple[int, int, int]:
    """Return (lo32, hi32, full64) for (|src0 - src1| + src2)."""
    diff = ref_abs_diff_u32(s0, s1)
    acc = s2 & MASK32
    sum64 = diff + acc
    lo = sum64 & MASK32
    hi = (sum64 >> 32) & MASK32
    return lo, hi, sum64


# ==============================================================================
# Unit Tests: Model and Reference Oracle
# ==============================================================================

class TestValuSadHiU32Oracle(unittest.TestCase):
    """Unit tests for RDNA2 v_sad_hi_u32 architectural bit model and reference oracle."""

    def test_known_vectors_basic(self) -> None:
        # Zero inputs -> 0
        self.assertEqual(ref_sad_hi_u32(0, 0, 0), 0)
        # Small difference without carry: |10 - 4| + 5 = 11 -> hi = 0
        self.assertEqual(ref_sad_hi_u32(10, 4, 5), 0)
        self.assertEqual(ref_sad_u32(10, 4, 5), 11)

    def test_carry_generation_exact_boundary(self) -> None:
        # diff = 0xFFFFFFFF, s2 = 0 -> sum = 0xFFFFFFFF, hi = 0
        lo, hi, full = ref_sad_full_64(0xFFFF_FFFF, 0, 0)
        self.assertEqual(lo, 0xFFFF_FFFF)
        self.assertEqual(hi, 0)
        self.assertEqual(full, 0xFFFF_FFFF)

        # diff = 0xFFFFFFFF, s2 = 1 -> sum = 0x100000000, hi = 1, lo = 0
        lo, hi, full = ref_sad_full_64(0xFFFF_FFFF, 0, 1)
        self.assertEqual(lo, 0)
        self.assertEqual(hi, 1)
        self.assertEqual(full, 0x1_0000_0000)

        # diff = 0x80000000, s2 = 0x80000000 -> sum = 0x100000000, hi = 1, lo = 0
        lo, hi, full = ref_sad_full_64(0x8000_0000, 0, 0x8000_0000)
        self.assertEqual(lo, 0)
        self.assertEqual(hi, 1)
        self.assertEqual(full, 0x1_0000_0000)

        # diff = 0x80000000, s2 = 0x7FFFFFFF -> sum = 0xFFFFFFFF, hi = 0, lo = 0xFFFFFFFF
        lo, hi, full = ref_sad_full_64(0x8000_0000, 0, 0x7FFF_FFFF)
        self.assertEqual(lo, 0xFFFF_FFFF)
        self.assertEqual(hi, 0)
        self.assertEqual(full, 0xFFFF_FFFF)

    def test_maximum_accumulation(self) -> None:
        # Maximum possible inputs: diff = 0xFFFFFFFF, s2 = 0xFFFFFFFF
        # sum64 = 0xFFFFFFFF + 0xFFFFFFFF = 0x1FFFFFFFE -> lo = 0xFFFFFFFE, hi = 1
        lo, hi, full = ref_sad_full_64(0xFFFF_FFFF, 0, 0xFFFF_FFFF)
        self.assertEqual(lo, 0xFFFF_FFFE)
        self.assertEqual(hi, 1)
        self.assertEqual(full, 0x1_FFFF_FFFE)

    def test_zero_difference_hi_is_always_zero(self) -> None:
        # When s0 == s1, |s0 - s1| = 0.
        # sum64 = 0 + s2 = s2 <= 0xFFFFFFFF. Thus hi is strictly 0 for all s2.
        test_values = [0, 1, 0x7FFF_FFFF, 0x8000_0000, 0xFFFF_FFFF, 0x1234_5678]
        for s2 in test_values:
            with self.subTest(s2=hex(s2)):
                self.assertEqual(ref_sad_hi_u32(0x1234_5678, 0x1234_5678, s2), 0)
                self.assertEqual(ref_sad_u32(0x1234_5678, 0x1234_5678, s2), s2)

    def test_commutativity_src0_src1(self) -> None:
        pairs = [
            (0, 0xFFFF_FFFF, 1),
            (0x100, 0x200, 0xFFFF_FFF0),
            (0xDEAD_BEEF, 0xCAFE_BABE, 0x8000_0000),
            (0x8000_0000, 0x0000_0001, 0xFFFF_FFFF),
            (0xAAAA_5555, 0x5555_AAAA, 0x7FFF_FFFF),
        ]
        for s0, s1, s2 in pairs:
            with self.subTest(s0=hex(s0), s1=hex(s1), s2=hex(s2)):
                self.assertEqual(ref_sad_hi_u32(s0, s1, s2), ref_sad_hi_u32(s1, s0, s2))
                self.assertEqual(ref_sad_u32(s0, s1, s2), ref_sad_u32(s1, s0, s2))

    def test_hi_bounded_in_zero_or_one(self) -> None:
        for s0 in [0, 1, 0x8000_0000, 0xFFFF_FFFF]:
            for s1 in [0, 1, 0x7FFF_FFFF, 0xFFFF_FFFF]:
                for s2 in [0, 1, 0x8000_0000, 0xFFFF_FFFF]:
                    hi = ref_sad_hi_u32(s0, s1, s2)
                    self.assertIn(hi, (0, 1))

    def test_full_64bit_sad_reconstruction(self) -> None:
        vectors = [
            (0x1234_5678, 0x9ABC_DEF0, 0x5555_5555),
            (0xFFFF_FFFF, 0x0000_0000, 0xFFFF_FFFF),
            (0x8000_0000, 0x7FFF_FFFF, 0x0000_0001),
            (0x0000_0000, 0x0000_0000, 0x0000_0000),
        ]
        for s0, s1, s2 in vectors:
            with self.subTest(s0=hex(s0), s1=hex(s1), s2=hex(s2)):
                lo = ref_sad_u32(s0, s1, s2)
                hi = ref_sad_hi_u32(s0, s1, s2)
                reconstructed = (hi << 32) | lo
                expected = ref_abs_diff_u32(s0, s1) + u32(s2)
                self.assertEqual(reconstructed, expected)


if __name__ == "__main__":
    unittest.main()
