"""Semantic interpreter tests for RDNA2 v_sad_hi_u32 (high 32 bits of sum of absolute differences).

AMD RDNA VALU Instruction Set Architecture (ISA):
  v_sad_hi_u32 dst, src0, src1, src2
  Operation (VOP3 3-operand vector ALU format):
    diff    = |src0 - src1| = max(src0, src1) - min(src0, src1)  (unsigned 32-bit difference)
    sum64   = diff + src2                                        (unsigned 64-bit accumulation)
    dst     = sum64 >> 32                                        (high 32 bits of 64-bit result)

Complementary VALU instruction:
  v_sad_u32 dst, src0, src1, src2
    dst     = sum64 & 0xFFFFFFFF                                 (low 32 bits of 64-bit result)

Mathematical properties and carry bounds:
  - Since src0, src1, src2 are unsigned 32-bit integers in [0, 2^32 - 1]:
      diff in [0, 2^32 - 1] = [0, 0xFFFFFFFF]
      sum64 in [0, 2 * (2^32 - 1)] = [0, 0x1FFFFFFFE]
  - Consequently, (sum64 >> 32) is strictly in {0, 1}.
  - v_sad_hi_u32 directly computes the carry-out generated by adding |src0 - src1| to src2.
  - Multi-precision 64-bit SAD reconstruction:
      (v_sad_hi_u32(s0, s1, s2) << 32) | v_sad_u32(s0, s1, s2) == |s0 - s1| + s2.

Standard library only: Python 3.9+ compatible, zero game data, zero proprietary assets.
"""
