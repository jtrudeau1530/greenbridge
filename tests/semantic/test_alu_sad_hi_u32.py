MASK32 = 0xFFFFFFFF
MASK64 = 0xFFFFFFFFFFFFFFFF


def u32(val: int) -> int:
    """Normalize integer to 32-bit unsigned word."""
    return val & MASK32


def u64(val: int) -> int:
    """Normalize integer to 64-bit unsigned word."""
    return val & MASK64


def ref_abs_diff_u32(s0: int, s1: int) -> int:
    """Pure-Python reference oracle for 32-bit unsigned absolute difference: |s0 - s1|."""
    a = u32(s0)
    b = u32(s1)
    return (a - b) if a >= b else (b - a)


def ref_sad_u32(s0: int, s1: int, s2: int) -> int:
    """Pure-Python reference oracle for RDNA2 v_sad_u32: (|s0 - s1| + s2) & 0xFFFFFFFF."""
    return u32(ref_abs_diff_u32(s0, s1) + u32(s2))


def ref_sad_hi_u32(s0: int, s1: int, s2: int) -> int:
    """Pure-Python reference oracle for RDNA2 v_sad_hi_u32: (|s0 - s1| + s2) >> 32."""
    sum64 = ref_abs_diff_u32(s0, s1) + u32(s2)
    return (sum64 >> 32) & MASK32


def ref_sad_full_64(s0: int, s1: int, s2: int) -> tuple[int, int, int]:
    """Return (lo32, hi32, full64) for (|s0 - s1| + s2)."""
    diff = ref_abs_diff_u32(s0, s1)
    sum64 = diff + u32(s2)
    lo = sum64 & MASK32
    hi = (sum64 >> 32) & MASK32
    return lo, hi, sum64


class SadHiValuInterpreter:
    """Lightweight deterministic semantic VALU interpreter modeling RDNA2 v_sad_hi_u32 and v_sad_u32.

    Maintains vector register banks (VGPRs 0..255) across configurable SIMD lanes (default 32 lanes),
    scalar register banks (SGPRs 0..105), and an execution mask (EXEC).
    """

    def __init__(self, num_lanes: int = 32, num_vgprs: int = 256, num_sgprs: int = 106) -> None:
        self.num_lanes = num_lanes
        self.num_vgprs = num_vgprs
        self.num_sgprs = num_sgprs
        self.vgprs: list[list[int]] = [[0] * num_vgprs for _ in range(num_lanes)]
        self.sgprs: list[int] = [0] * num_sgprs
        self.exec_mask: int = (1 << num_lanes) - 1

    def reset(self) -> None:
        """Reset all register banks and set EXEC mask to all lanes active."""
        for lane in range(self.num_lanes):
            self.vgprs[lane] = [0] * self.num_vgprs
        self.sgprs = [0] * self.num_sgprs
        self.exec_mask = (1 << self.num_lanes) - 1

    def set_vgpr(self, lane: int, reg_idx: int, val: int) -> None:
        """Set a single lane VGPR value."""
        if not (0 <= lane < self.num_lanes):
            raise IndexError(f"Lane {lane} out of range [0, {self.num_lanes})")
        if not (0 <= reg_idx < self.num_vgprs):
            raise IndexError(f"VGPR index v{reg_idx} out of range [0, {self.num_vgprs})")
        self.vgprs[lane][reg_idx] = u32(val)

    def get_vgpr(self, lane: int, reg_idx: int) -> int:
        """Get a single lane VGPR value."""
        if not (0 <= lane < self.num_lanes):
            raise IndexError(f"Lane {lane} out of range [0, {self.num_lanes})")
        if not (0 <= reg_idx < self.num_vgprs):
            raise IndexError(f"VGPR index v{reg_idx} out of range [0, {self.num_vgprs})")
        return self.vgprs[lane][reg_idx]

    def set_vgpr_all(self, reg_idx: int, val: int) -> None:
        """Broadcast a 32-bit unsigned integer to a VGPR across all lanes."""
        v = u32(val)
        for lane in range(self.num_lanes):
            self.set_vgpr(lane, reg_idx, v)

    def set_sgpr(self, reg_idx: int, val: int) -> None:
        """Set an SGPR value."""
        if not (0 <= reg_idx < self.num_sgprs):
            raise IndexError(f"SGPR index s{reg_idx} out of range [0, {self.num_sgprs})")
        self.sgprs[reg_idx] = u32(val)

    def get_sgpr(self, reg_idx: int) -> int:
        """Get an SGPR value."""
        if not (0 <= reg_idx < self.num_sgprs):
            raise IndexError(f"SGPR index s{reg_idx} out of range [0, {self.num_sgprs})")
        return self.sgprs[reg_idx]

    def parse_operand(self, token: str, lane: int) -> int:
        """Parse register, hex, or decimal token into a 32-bit unsigned value for a given lane."""
        token = token.strip().rstrip(",")
        if not token:
            raise ValueError("Empty operand token")
        low = token.lower()
        if low.startswith("v") and low[1:].isdigit():
            idx = int(low[1:])
            return self.get_vgpr(lane, idx)
        if low.startswith("s") and low[1:].isdigit():
            idx = int(low[1:])
            return self.get_sgpr(idx)
        if low.startswith("0x") or low.startswith("-0x"):
            return u32(int(token, 16))
        try:
            return u32(int(token, 10))
        except ValueError:
            raise ValueError(f"Invalid operand token: {token}")

    def execute_line(self, line: str) -> None:
        """Execute a single VALU/SALU instruction string."""
        line = line.split(";", 1)[0].split("//", 1)[0].strip()
        if not line:
            return
        parts = line.replace(",", " ").split()
        opcode = parts[0].lower()
        operands = parts[1:]

        if opcode == "v_mov_b32":
            if len(operands) != 2:
                raise ValueError(f"v_mov_b32 requires 2 operands, got: {operands}")
            dst_token = operands[0].lower()
            if not (dst_token.startswith("v") and dst_token[1:].isdigit()):
                raise ValueError(f"Destination must be VGPR: {dst_token}")
            dst_idx = int(dst_token[1:])
            for lane in range(self.num_lanes):
                if (self.exec_mask & (1 << lane)) != 0:
                    val = self.parse_operand(operands[1], lane)
                    self.set_vgpr(lane, dst_idx, val)

        elif opcode == "s_mov_b32":
            if len(operands) != 2:
                raise ValueError(f"s_mov_b32 requires 2 operands, got: {operands}")
            dst_token = operands[0].lower()
            if dst_token == "exec_lo":
                val = self.parse_operand(operands[1], 0)
                self.exec_mask = (self.exec_mask & ~0xFFFFFFFF) | val
                return
            if dst_token == "exec_hi":
                val = self.parse_operand(operands[1], 0)
                self.exec_mask = (self.exec_mask & 0xFFFFFFFF) | (val << 32)
                return
            if dst_token == "exec":
                val = self.parse_operand(operands[1], 0)
                self.exec_mask = val
                return
            if not (dst_token.startswith("s") and dst_token[1:].isdigit()):
                raise ValueError(f"Destination must be SGPR: {dst_token}")
            dst_idx = int(dst_token[1:])
            val = self.parse_operand(operands[1], 0)
            self.set_sgpr(dst_idx, val)

        elif opcode in ("v_sad_hi_u32", "v_sad_u32"):
            if any(opt.lower() == "clamp" for opt in operands):
                raise ValueError(f"{opcode} clamp is unsupported in RDNA2 ISA")
            if len(operands) != 4:
                raise ValueError(f"{opcode} requires 4 operands (dst, s0, s1, s2), got: {operands}")
            dst_token = operands[0].lower()
            if not (dst_token.startswith("v") and dst_token[1:].isdigit()):
                raise ValueError(f"Destination must be VGPR: {dst_token}")
            dst_idx = int(dst_token[1:])

            for lane in range(self.num_lanes):
                if (self.exec_mask & (1 << lane)) != 0:
                    s0 = self.parse_operand(operands[1], lane)
                    s1 = self.parse_operand(operands[2], lane)
                    s2 = self.parse_operand(operands[3], lane)
                    if opcode == "v_sad_hi_u32":
                        res = ref_sad_hi_u32(s0, s1, s2)
                    else:
                        res = ref_sad_u32(s0, s1, s2)
                    self.set_vgpr(lane, dst_idx, res)

        elif opcode == "v_add_u32":
            if len(operands) != 3:
                raise ValueError(f"v_add_u32 requires 3 operands, got: {operands}")
            dst_token = operands[0].lower()
            if not (dst_token.startswith("v") and dst_token[1:].isdigit()):
                raise ValueError(f"Destination must be VGPR: {dst_token}")
            dst_idx = int(dst_token[1:])
            for lane in range(self.num_lanes):
                if (self.exec_mask & (1 << lane)) != 0:
                    s0 = self.parse_operand(operands[1], lane)
                    s1 = self.parse_operand(operands[2], lane)
                    self.set_vgpr(lane, dst_idx, u32(s0 + s1))

        else:
            raise NotImplementedError(f"Opcode {opcode} not implemented in test interpreter")

    def run_program(self, lines: list[str]) -> None:
        """Execute a sequence of assembly lines."""
        for line in lines:
            self.execute_line(line)


def run_spirv_sad_hi(s0: int, s1: int, s2: int) -> tuple[int, int]:
    """Execute v_sad_u32 and v_sad_hi_u32 lowered to SPIR-V via spirv_mini_interp.

    Returns (lo32, hi32).
    """
    spv_text = f"""OpCapability Shader
OpMemoryModel Logical GLSL450
OpEntryPoint Fragment %main "main" %out_mrt0
OpExecutionMode %main OriginUpperLeft
OpDecorate %out_mrt0 Location 0
%void = OpTypeVoid
%fn = OpTypeFunction %void
%uint = OpTypeInt 32 0
%v4uint = OpTypeVector %uint 4
%pout = OpTypePointer Output %v4uint
%struct_u32_u32 = OpTypeStruct %uint %uint
%out_mrt0 = OpVariable %pout Output
%glsl = OpExtInstImport "GLSL.std.450"
%s0 = OpConstant %uint {u32(s0)}
%s1 = OpConstant %uint {u32(s1)}
%s2 = OpConstant %uint {u32(s2)}
%c0 = OpConstant %uint 0
%main = OpFunction %void None %fn
%entry = OpLabel
%max = OpExtInst %uint %glsl UMax %s0 %s1
%min = OpExtInst %uint %glsl UMin %s0 %s1
%diff = OpISub %uint %max %min
%addcarry = OpIAddCarry %struct_u32_u32 %diff %s2
%res_lo = OpCompositeExtract %uint %addcarry 0
%res_hi = OpCompositeExtract %uint %addcarry 1
%out_vec = OpCompositeConstruct %v4uint %res_lo %res_hi %c0 %c0
OpStore %out_mrt0 %out_vec
OpReturn
OpFunctionEnd
"""
    res = si.run_fragment(spv_text)
    out = res["%out_mrt0"]
    return out[0], out[1]


class TestSadHiReferenceOracle(unittest.TestCase):
    """Verifies the pure-Python reference oracle against the mathematical specification."""

    def test_basic_arithmetic(self):
        # Case 1: No carry generated
        # |10 - 4| + 5 = 6 + 5 = 11 -> lo = 11, hi = 0
        lo, hi, full = ref_sad_full_64(10, 4, 5)
        self.assertEqual(lo, 11)
        self.assertEqual(hi, 0)
        self.assertEqual(full, 11)
        self.assertEqual(ref_sad_hi_u32(10, 4, 5), 0)
        self.assertEqual(ref_sad_u32(10, 4, 5), 11)

    def test_carry_threshold_boundary(self):
        # Boundary: diff + s2 = 0xFFFFFFFF (no carry)
        # s0 = 0xFFFFFFFF, s1 = 0 -> diff = 0xFFFFFFFF. S2 = 0 -> sum = 0xFFFFFFFF
        lo, hi, full = ref_sad_full_64(0xFFFFFFFF, 0, 0)
        self.assertEqual(lo, 0xFFFFFFFF)
        self.assertEqual(hi, 0)
        self.assertEqual(full, 0xFFFFFFFF)

        # Boundary: diff + s2 = 0x100000000 (carry out = 1, lo = 0)
        lo, hi, full = ref_sad_full_64(0xFFFFFFFF, 0, 1)
        self.assertEqual(lo, 0)
        self.assertEqual(hi, 1)
        self.assertEqual(full, 0x100000000)

    def test_maximum_accumulation(self):
        # Maximum possible inputs: diff = 0xFFFFFFFF, S2 = 0xFFFFFFFF
        # sum64 = 0xFFFFFFFF + 0xFFFFFFFF = 0x1FFFFFFFE -> lo = 0xFFFFFFFE, hi = 1
        lo, hi, full = ref_sad_full_64(0xFFFFFFFF, 0, 0xFFFFFFFF)
        self.assertEqual(lo, 0xFFFFFFFE)
        self.assertEqual(hi, 1)
        self.assertEqual(full, 0x1FFFFFFFE)

    def test_zero_difference_invariance(self):
        # When s0 == s1, |s0 - s1| = 0. Then (|s0 - s1| + s2) = s2.
        # Since s2 <= 0xFFFFFFFF, sum64 <= 0xFFFFFFFF, so hi is ALWAYS 0.
        for s2 in [0, 1, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF]:
            with self.subTest(s2=hex(s2)):
                self.assertEqual(ref_sad_hi_u32(0x12345678, 0x12345678, s2), 0)
                self.assertEqual(ref_sad_u32(0x12345678, 0x12345678, s2), s2)

    def test_commutative_operands(self):
        # |s0 - s1| is commutative: ref_sad_hi_u32(s0, s1, s2) == ref_sad_hi_u32(s1, s0, s2)
        pairs = [
            (0, 0xFFFFFFFF, 1),
            (0x100, 0x200, 0xFFFFFFF0),
            (0xDEADBEEF, 0xCAFEBABE, 0x80000000),
            (0x80000000, 0x00000001, 0xFFFFFFFF),
        ]
        for s0, s1, s2 in pairs:
            with self.subTest(s0=hex(s0), s1=hex(s1), s2=hex(s2)):
                self.assertEqual(ref_sad_hi_u32(s0, s1, s2), ref_sad_hi_u32(s1, s0, s2))
                self.assertEqual(ref_sad_u32(s0, s1, s2), ref_sad_u32(s1, s0, s2))


class TestSadHiValuInterpreter(unittest.TestCase):
    """Tests execution in the SadHiValuInterpreter."""

    def setUp(self):
        self.interp = SadHiValuInterpreter(num_lanes=1)

    def test_interpreter_basic_registers(self):
        # v0 = v_sad_hi_u32 v1, v2, v3
        self.interp.run_program([
            "v_mov_b32 v1, 0xFFFFFFFF",
            "v_mov_b32 v2, 0x00000000",
            "v_mov_b32 v3, 0x00000001",
            "v_sad_hi_u32 v0, v1, v2, v3",
            "v_sad_u32 v4, v1, v2, v3",
        ])
        self.assertEqual(self.interp.get_vgpr(0, 0), 1)
        self.assertEqual(self.interp.get_vgpr(0, 4), 0)

    def test_interpreter_sgpr_sources(self):
        # v_sad_hi_u32 can read SGPR operands
        self.interp.run_program([
            "s_mov_b32 s0, 0x80000000",
            "s_mov_b32 s1, 0x00000000",
            "s_mov_b32 s2, 0x80000000",
            "v_sad_hi_u32 v0, s0, s1, s2",
            "v_sad_u32 v1, s0, s1, s2",
        ])
        # |0x80000000 - 0| + 0x80000000 = 0x100000000 -> carry = 1, sum_lo = 0
        self.assertEqual(self.interp.get_vgpr(0, 0), 1)
        self.assertEqual(self.interp.get_vgpr(0, 1), 0)

    def test_interpreter_inline_literals(self):
        self.interp.run_program([
            "v_mov_b32 v1, 0x7FFFFFFF",
            "v_sad_hi_u32 v0, v1, 0, 0x80000001",
        ])
        # |0x7FFFFFFF - 0| + 0x80000001 = 0x100000000 -> carry = 1
        self.assertEqual(self.interp.get_vgpr(0, 0), 1)

    def test_interpreter_in_place_destination_overwrite(self):
        # Overwrite S0
        self.interp.run_program([
            "v_mov_b32 v0, 0xFFFFFFFF",
            "v_mov_b32 v1, 0x00000000",
            "v_mov_b32 v2, 0x00000001",
            "v_sad_hi_u32 v0, v0, v1, v2",
        ])
        self.assertEqual(self.interp.get_vgpr(0, 0), 1)

        # Overwrite S2
        self.interp.run_program([
            "v_mov_b32 v0, 0xFFFFFFFF",
            "v_mov_b32 v1, 0x00000000",
            "v_mov_b32 v2, 0x00000001",
            "v_sad_hi_u32 v2, v0, v1, v2",
        ])
        self.assertEqual(self.interp.get_vgpr(0, 2), 1)


class TestSadHiSpirvLowering(unittest.TestCase):
    """Verifies translation to SPIR-V using OpIAddCarry executed by spirv_mini_interp."""

    def test_spirv_mini_interp_parity(self):
        test_vectors = [
            (0, 0, 0),
            (10, 4, 5),
            (0xFFFFFFFF, 0, 0),
            (0xFFFFFFFF, 0, 1),
            (0xFFFFFFFF, 0, 0xFFFFFFFF),
            (0x12345678, 0x87654321, 0xEEEEEEEE),
            (0x80000000, 0x00000001, 0xFFFFFFFF),
            (0xAAAA5555, 0x5555AAAA, 0x80000000),
        ]
        for s0, s1, s2 in test_vectors:
            with self.subTest(s0=hex(s0), s1=hex(s1), s2=hex(s2)):
                spv_lo, spv_hi = run_spirv_sad_hi(s0, s1, s2)
                self.assertEqual(spv_lo, ref_sad_u32(s0, s1, s2))
                self.assertEqual(spv_hi, ref_sad_hi_u32(s0, s1, s2))


